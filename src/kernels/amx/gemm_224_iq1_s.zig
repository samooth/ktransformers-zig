const init_mod = @import("iq2xs_init.zig");

fn nearestInt(fval: f32) i32 {
    std.debug.assert(@abs(fval) <= 4194303.0);
    const val: f32 = fval + 12582912.0;
    const i: i32 = @bitCast(val);
    return (i & 0x007f_ffff) - 0x0040_0000;
}

const GROUP_MAX_EPS: f32 = 1e-15; // GROUP_MAX_EPS_IQ1_S (ggml-quants.c:23)

/// iq1_find_best_neighbour2 (ggml:4443): try the kneighbors entries
/// against the xg[] delta-shifted levels; FALL BACK to an exhaustive
/// 2048-entry scan if no neighbor beats FLT_MAX (some 1-bit
/// fingerprints have empty neighbor lists).
fn findBestNeighbour2(
    data: *const init_mod.Iq2GridData,
    neighbors_start: usize,
    xval: []const f32,
    weight: []const f32,
    scale: f32,
    xg: [3]f32,
    L: [*]u8,
) usize {
    const num_neighbors = data.kneighbors[neighbors_start];
    var best_score: f32 = std.math.floatMax(f32);
    var grid_index: usize = std.math.maxInt(usize);

    if (num_neighbors > 0) {
        for (1..num_neighbors + 1) |j| {
            const nb = data.kneighbors[neighbors_start + j];
            const gpos = data.grid[nb];
            var d2: f32 = 0;
            for (0..8) |i| {
                const q: f32 = xg[@intCast(@divTrunc(gpos[i] - 1, 2))];
                const diff = scale * q - xval[i];
                const w = weight[i];
                d2 += w * diff * diff;
            }
            if (d2 < best_score) {
                best_score = d2;
                grid_index = nb;
            }
        }
    }
    if (grid_index == std.math.maxInt(usize)) {
        // Exhaustive fallback over the whole 2048-entry grid.
        for (0..2048) |i| {
            const gpos = data.grid[i];
            var d2: f32 = 0;
            for (0..8) |j| {
                const q: f32 = xg[@intCast(@divTrunc(gpos[j] - 1, 2))];
                const w = weight[j];
                const diff = scale * q - xval[j];
                d2 += w * diff * diff;
            }
            if (d2 < best_score) {
                best_score = d2;
                grid_index = i;
            }
        }
    }
    std.debug.assert(grid_index != std.math.maxInt(usize));
    const gpos = data.grid[grid_index];
    for (0..8) |i| L[i] = @intCast(@divTrunc(gpos[i] - 1, 2));
    return grid_index;
}

/// Quantize a full row using the 2048-entry 1-bit kmap (nwant=3).
/// Caller must call init_mod.initIq1SData first.
pub fn quantizeRowIQ1_S_WithInit(
    data: *const init_mod.Iq2GridData,
    src: []const f32,
    dst: [*]BlockIQ1_S,
    k: usize,
    quant_weights: ?[]const f32,
) void {
    const block_size = IQ1S_BLOCK_SIZE;
    std.debug.assert(k % QK_K == 0);
    const nb = k / QK_K;

    const x_p = [3]f32{ -1.0 + IQ1S_DELTA, IQ1S_DELTA, 1.0 + IQ1S_DELTA };
    const x_m = [3]f32{ -1.0 - IQ1S_DELTA, -IQ1S_DELTA, 1.0 - IQ1S_DELTA };

    var scales: [QK_K / block_size]f32 = undefined;
    var weight: [block_size]f32 = undefined;
    var sumx: [block_size + 1]f32 = undefined;
    var sumw: [block_size + 1]f32 = undefined;
    // pairs: interleaved (value, index) — sorted by value; idx aliases the
    // second half like the C (pairs + 1 int offset).
    var pairs: [2 * block_size]f32 = undefined;
    var L: [block_size]u8 = undefined;
    var index: [block_size / 8]u16 = undefined;
    var shifts: [QK_K / block_size]i8 = undefined;

    for (0..nb) |ibl| {
        const blk = &dst[ibl];
        blk.d = f32_to_f16(0.0);
        @memset(blk.qs[0..], 0);
        @memset(blk.qh[0..], 0);

        var max_scale: f32 = 0;
        const xbl = src[ibl * QK_K ..][0..QK_K];

        var sumx2: f32 = 0;
        for (0..QK_K) |i| sumx2 += xbl[i] * xbl[i];
        const sigma2 = 2 * sumx2 / QK_K;

        for (0..QK_K / block_size) |ib| {
            const xb = xbl[block_size * ib ..][0..block_size];

            // Null quant_weights: |x| (the reference asserts non-null).
            for (0..block_size) |i| {
                weight[i] = if (quant_weights) |qwv| qwv[ibl * QK_K + block_size * ib + i] * @sqrt(sigma2 + xb[i] * xb[i]) else @abs(xb[i]);
            }
            var max: f32 = @abs(xb[0]);
            for (1..block_size) |i| max = @max(max, @abs(xb[i]));
            if (max < GROUP_MAX_EPS) {
                scales[ib] = 0;
                shifts[ib] = 1;
                @memset(L[0..block_size], 1);
                continue;
            }

            // Sort (value, original-index) pairs ascending (iq1_sort_helper).
            for (0..block_size) |j| {
                pairs[2 * j] = xb[j];
                const idx_bits: u32 = @intCast(j);
                pairs[2 * j + 1] = @bitCast(idx_bits);
            }
            std.mem.sort([2]f32, @as([][2]f32, @ptrCast(pairs[0 .. 2 * block_size]))[0..block_size], {}, struct {
                fn lt(_: void, a: [2]f32, b: [2]f32) bool {
                    return a[0] < b[0];
                }
            }.lt);

            // Prefix sums over the sorted order.
            sumx[0] = 0;
            sumw[0] = 0;
            for (0..block_size) |j| {
                const i: usize = @as(u32, @bitCast(pairs[2 * j + 1]));
                sumx[j + 1] = sumx[j] + weight[i] * xb[i];
                sumw[j + 1] = sumw[j] + weight[i];
            }

            // Exhaustive 2-boundary SSD search over both delta shifts.
            var best_score: f32 = -std.math.floatMax(f32);
            var scale = max;
            var besti1: i32 = -1;
            var besti2: i32 = -1;
            var best_shift: i32 = 0;
            var b1: usize = 0;
            while (b1 <= block_size) : (b1 += 1) {
                var b2: usize = b1;
                while (b2 <= block_size) : (b2 += 1) {
                    // shift +1 (x_p)
                    {
                        const sumqx = (sumx[b1] - sumx[0]) * x_p[0] + (sumx[b2] - sumx[b1]) * x_p[1] + (sumx[block_size] - sumx[b2]) * x_p[2];
                        const sumq2 = (sumw[b1] - sumw[0]) * x_p[0] * x_p[0] + (sumw[b2] - sumw[b1]) * x_p[1] * x_p[1] + (sumw[block_size] - sumw[b2]) * x_p[2] * x_p[2];
                        if (sumq2 > 0 and sumqx * sumqx > best_score * sumq2) {
                            scale = sumqx / sumq2;
                            best_score = scale * sumqx;
                            besti1 = @intCast(b1);
                            besti2 = @intCast(b2);
                            best_shift = 1;
                        }
                    }
                    // shift -1 (x_m)
                    {
                        const sumqx = (sumx[b1] - sumx[0]) * x_m[0] + (sumx[b2] - sumx[b1]) * x_m[1] + (sumx[block_size] - sumx[b2]) * x_m[2];
                        const sumq2 = (sumw[b1] - sumw[0]) * x_m[0] * x_m[0] + (sumw[b2] - sumw[b1]) * x_m[1] * x_m[1] + (sumw[block_size] - sumw[b2]) * x_m[2] * x_m[2];
                        if (sumq2 > 0 and sumqx * sumqx > best_score * sumq2) {
                            scale = sumqx / sumq2;
                            best_score = scale * sumqx;
                            besti1 = @intCast(b1);
                            besti2 = @intCast(b2);
                            best_shift = -1;
                        }
                    }
                }
            }
            if (besti1 < 0 or besti2 < 0 or best_shift == 0) {
                scales[ib] = 0;
                shifts[ib] = 1;
                @memset(L[0..block_size], 1);
                continue;
            }

            // Levels from the sorted splits.
            for (0..@intCast(besti1)) |j| {
                const i: usize = @as(u32, @bitCast(pairs[2 * j + 1]));
                L[i] = 0;
            }
            for (@as(usize, @intCast(besti1))..@as(usize, @intCast(besti2))) |j| {
                const i: usize = @as(u32, @bitCast(pairs[2 * j + 1]));
                L[i] = 1;
            }
            for (@as(usize, @intCast(besti2))..block_size) |j| {
                const i: usize = @as(u32, @bitCast(pairs[2 * j + 1]));
                L[i] = 2;
            }
            if (scale < 0) {
                for (0..block_size) |j| L[j] = 2 - L[j];
                scale = -scale;
                best_shift = -best_shift;
            }

            // Grid lookup per 8-sub-block (with the exhaustive fallback).
            const xx: [3]f32 = if (best_shift == 1) x_p else x_m;
            var all_on_grid = true;
            for (0..block_size / 8) |kk| {
                var u: u16 = 0;
                for (0..8) |j| u |= @as(u16, L[8 * kk + j]) << @intCast(2 * j);
                if (data.kmap[u] >= 0) {
                    index[kk] = @intCast(data.kmap[u]);
                } else {
                    all_on_grid = false;
                    const enc = data.kmap[u];
                    const nb_start: usize = @intCast(-(enc + 1));
                    index[kk] = @intCast(findBestNeighbour2(data, nb_start, xb[8 * kk ..][0..8], weight[8 * kk ..][0..8], scale, xx, L[8 * kk ..].ptr));
                }
            }
            if (!all_on_grid) {
                // NOTE: read the RUNTIME position grid (data.grid, bytes
                // {1,3,5}) — NOT IQ1S_GRID (dequant bytes {-1,0,1}).
                // (pg-1)/2 maps positions to xg indices; applying it to
                // the dequant bytes overflows (found by the round-trip
                // test's integer-overflow panic at the @intCast).
                var sumqx: f32 = 0;
                var sumq2: f32 = 0;
                for (0..block_size / 8) |kk| {
                    const gpos = data.grid[index[kk]];
                    for (0..8) |j| {
                        const w = weight[8 * kk + j];
                        const q = xx[@intCast(@divTrunc(gpos[j] - 1, 2))];
                        sumqx += w * q * xb[8 * kk + j];
                        sumq2 += w * q * q;
                    }
                }
                if (sumqx > 0 and sumq2 > 0) scale = sumqx / sumq2;
            }

            // Pack index-lo into qs, index-hi (3 bits x 4) into the low
            // 12 bits of qh[ib].
            var h: u16 = 0;
            for (0..block_size / 8) |kk| {
                blk.qs[(block_size / 8) * ib + kk] = @truncate(index[kk]);
                h |= @as(u16, @truncate(index[kk] >> 8)) << @intCast(3 * kk);
            }
            blk.qh[ib] = h;

            scales[ib] = scale;
            shifts[ib] = @intCast(best_shift);
            max_scale = @max(max_scale, scale);
        }

        if (max_scale == 0) {
            continue;
        }

        const d = max_scale / 15.0;
        blk.d = f32_to_f16(d * 1.125); // 1.125 fudge (ggml:4661, "Don't ask")
        const id = 1.0 / d;
        for (0..QK_K / block_size) |ib| {
            var l = nearestInt(0.5 * (id * scales[ib] - 1));
            l = std.math.clamp(l, 0, 7);
            var lu: u16 = @intCast(l);
            if (shifts[ib] == -1) lu |= 8;
            blk.qh[ib] |= lu << 12;
        }
    }
}
