pub fn f32_to_f16(x: f32) u16 {
    const h: f16 = @floatCast(x);
    return @bitCast(h);
}

pub fn f16_to_f32(x: u16) f32 {
    const h: f16 = @bitCast(x);
    return @floatCast(h);
}

/// Read the 8 int8 magnitude bytes of a grid entry (LE: byte j is
/// (u64 >> 8*j) & 0xff, interpreted as i8).
inline fn gridBytes(entry: u64) [8]i8 {
    var out: [8]i8 = undefined;
    inline for (0..8) |j| {
        out[j] = @bitCast(@as(u8, @truncate(entry >> @intCast(8 * j))));
    }
    return out;
}

// ============================================================================
// Dequantize (byte-exact vs ggml-quants.c:2651)
// ============================================================================

/// k must be a multiple of 256.
pub fn dequantizeRowIQ1_S(x: [*]const BlockIQ1_S, y: [*]f32, k: usize) void {
    const nb = k / QK_K;
    var yoff: usize = 0;

    for (0..nb) |i| {
        const blk = &x[i];
        const d = f16_to_f32(blk.d);

        for (0..QK_K / 32) |ib| {
            const word: u16 = blk.qh[ib];
            const dl = d * (2.0 * @as(f32, @floatFromInt((word >> 12) & 7)) + 1.0);
            const delta: f32 = if ((word & 0x8000) != 0) -IQ1S_DELTA else IQ1S_DELTA;

            for (0..4) |l| {
                const lo: usize = blk.qs[4 * ib + l];
                const hi: usize = @as(usize, (word >> @intCast(3 * l)) & 7) << 8;
                const entry: u64 = IQ1S_GRID[lo | hi];
                const gb = gridBytes(entry);

                for (0..8) |j| {
                    const q: f32 = @floatFromInt(gb[j]);
                    y[yoff + j] = dl * (q + delta);
                }
                yoff += 8;
            }
        }
    }
}

/// Dequantize IQ1_S to BF16.
pub fn dequantizeRowIQ1_SToBF16(x: [*]const BlockIQ1_S, y: [*]amx.bf16, k: usize) void {
    const nb = k / QK_K;
    var f: [QK_K]f32 = undefined;
    for (0..nb) |i| {
        dequantizeRowIQ1_S(x + i, &f, QK_K);
        for (0..QK_K) |j| y[i * QK_K + j] = amx.f32_to_bf16(f[j]);
    }
}

// ============================================================================
// Scalar GEMM (BF16 activations x IQ1_S weights -> F32)
// ============================================================================

pub fn gemmIQ1_SScalar(
    a: [*]const amx.bf16,
    b: [*]const BlockIQ1_S,
    c: [*]f32,
    m: usize,
    n: usize,
    k: usize,
    lda: usize,
    ldb: usize,
    ldc: usize,
) void {
    const nb = k / QK_K;
    var scratch: [QK_K]f32 = undefined;
    for (0..m) |i| {
        for (0..n) |j| {
            var sum: f32 = 0;
            for (0..nb) |blk| {
                dequantizeRowIQ1_S(b + j * ldb + blk, &scratch, QK_K);
                for (0..QK_K) |k0| {
                    sum += amx.bf16_to_f32(a[i * lda + k0]) * scratch[k0];
                }
            }
            c[i * ldc + j] = sum;
        }
    }
}

