// ============================================================================
// IQ1_S Block Structure (byte-exact vs ggml's block_iq1_s)
// ============================================================================

pub const QK_K: usize = 256;
const IQ1S_BLOCK_SIZE: usize = 32;
const IQ1S_DELTA: f32 = 0.125;

pub const BlockIQ1_S = extern struct {
    d: u16, // f16 global scale
    qs: [QK_K / 8]u8, // 32 grid-index lo bytes
    qh: [QK_K / 32]u16, // 8: per-group index-his(12b) + scale(3b) + delta(1b)
};

comptime {
    if (@sizeOf(BlockIQ1_S) != 50) @compileError("BlockIQ1_S must be 50 bytes");
}

