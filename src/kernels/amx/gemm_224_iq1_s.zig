// GEMM Kernel 224 IQ1_S (GGML non-linear 1.5625-bpw grid quant)
//
// Canonical GGUF layout (llama.cpp ggml-common.h, QK_K = 256,
// IQ1S_BLOCK_SIZE = 32):
//   block_iq1_s {
//     ggml_half d;           // 2 bytes: global super-block scale
//     uint8_t  qs[QK_K/8];   // 32 bytes: grid-index lo bytes (1 per 8 weights)
//     uint16_t qh[QK_K/32];  // 16 bytes: 8 x 3-bit index-his (low 12 bits)
//                            //         + 3-bit scale (bits 12..14)
//                            //         + delta-sign bit (bit 15)
//   } = 50 bytes per 256 weights
//
// Weight reconstruction (ggml-quants.c:2651):
//   Per 32-weight group (ib), 4 sub-blocks of 8:
//     dl    = d * (2*((qh[ib] >> 12) & 7) + 1)
//     delta = (qh[ib] & 0x8000) ? -0.125 : +0.125   (IQ1S_DELTA)
//     Per sub-block l: index = qs[l] | (((qh[ib] >> 3*l) & 7) << 8)
//       grid = iq1s_grid[index]  // 8 packed INT8 bytes: -1/0/+1
//       y[j] = dl * (grid[j] + delta)     // <- the DELTA shifts the
//                                        //    3-level code off the
//                                        //    lattice so the effective
//                                        //    values are {-1.125, 0.125,
//                                        //    1.125} or their negation
//
// The quantizer (ggml:4508-4670) is EXACT — no grid search:
//   With 3 allowed values it solves the weighted SSD minimization
//   exhaustively: sort the 32 |x| (qsort of (value, index) pairs),
//   prefix sums Si = sum[w*x], Wi = sum[w], then try every pair of
//   split boundaries (i1, i2) against BOTH delta shifts (x_p = code+δ,
//   x_m = code-δ) and keep the best sumqx^2 > best*sumq2.
//   L levels {0,1,2} -> grid nibble via the inverse map; off-grid
//   fingerprints go through iq1_find_best_neighbour2 (which FALLS BACK
//   to an exhaustive 2048-entry scan if the kneighbors list is empty).

